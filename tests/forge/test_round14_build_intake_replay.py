class TestRound14Replay:

    @pytest.mark.asyncio
    async def test_fixed_consumer_passes_gates_and_reaches_dispatch(self) -> None:
        """Post-fix: the same envelope clears gates 2 (originator) AND 3
        (path allowlist) and reaches the dispatch / pre-dispatch-approval
        path — no build-failed, no premature ack."""
        deps, mocks = _consumer_deps()
        msg = _make_msg(_load_fixture_bytes())

        await handle_message(msg, deps)

        # Gate 2 + gate 3 passed: dispatch_build was invoked with the parsed
        # payload (the pre-dispatch approval gate lives inside dispatch_build).
        mocks["dispatch_build"].assert_awaited_once()
        sent_payload = mocks["dispatch_build"].await_args.args[0]
        assert isinstance(sent_payload, BuildQueuedPayload)
        assert sent_payload.feature_id == FEATURE_ID
        assert sent_payload.triggered_by == "forge-internal"
        # No rejection published; the ack is deferred to the state machine.
        mocks["publish_build_failed"].assert_not_called()
        msg.ack.assert_not_called()


