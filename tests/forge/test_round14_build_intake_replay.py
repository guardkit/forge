def _payload_dict(**overrides: Any) -> dict[str, Any]:
    base: dict[str, Any] = {
        "feature_id": FEATURE_ID,
        "repo": TARGET_REPO,
        "branch": BRANCH,
        "feature_yaml_path": EXPECTED_FEATURE_YAML_PATH,
        "triggered_by": "forge-internal",
        "originating_adapter": None,
        "originating_user": ORIGINATING_USER,
        "correlation_id": CORRELATION_ID,
        "requested_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "queued_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "mode": "mode-b",
    }
    base.update(overrides)
    return base


def _envelope_bytes(payload: dict[str, Any]) -> bytes:
    envelope = MessageEnvelope(
        source_id="forge",
        event_type=EventType.BUILD_QUEUED,
        correlation_id=CORRELATION_ID,
        payload=payload,
    )
    return envelope.model_dump_json().encode("utf-8")


class TestMachineDispatchOriginatorGate:
    @pytest.mark.asyncio
    async def test_jarvis_adapter_in_list_is_accepted(self) -> None:
        payload = _payload_dict(
            triggered_by="jarvis",
            originating_adapter="slack",
        )
        deps, mocks = _consumer_deps()
        msg = _make_msg(_envelope_bytes(payload))

        await handle_message(msg, deps)

        mocks["dispatch_build"].assert_awaited_once()
        mocks["publish_build_failed"].assert_not_called()

    def test_jarvis_without_adapter_is_impossible_at_payload_layer(self) -> None:
        """The stricter jarvis invariant is enforced by nats-core's own
        validator, one layer below the consumer — so the consumer never has
        to special-case a None-adapter jarvis build."""
        with pytest.raises(ValidationError):
            BuildQueuedPayload.model_validate(
                _payload_dict(triggered_by="jarvis", originating_adapter=None)
            )


    @pytest.mark.asyncio
    async def test_duplicate_terminal_machine_dispatch_is_skipped(self) -> None:
        """Duplicate-terminal skip is unchanged for the machine dispatch: the
        build is acked and NOT dispatched, no failure published."""
        deps, mocks = _consumer_deps(is_duplicate_terminal=True)
        msg = _make_msg(_envelope_bytes(_payload_dict()))

        await handle_message(msg, deps)

        msg.ack.assert_awaited_once()
        mocks["dispatch_build"].assert_not_called()
        mocks["publish_build_failed"].assert_not_called()
