class TestFixtureProvenance:
    def test_committed_fixture_parses_and_carries_the_defect_shape(self) -> None:
        env = MessageEnvelope.model_validate_json(_load_fixture_bytes())
        payload = BuildQueuedPayload.model_validate(env.payload)
        assert payload.feature_id == FEATURE_ID
        assert payload.repo == TARGET_REPO
        assert payload.triggered_by == "forge-internal"
        # The exact shape that tripped the round-14 gate: a machine dispatch
        # with NO originating_adapter.
        assert payload.originating_adapter is None
        assert payload.originating_user == ORIGINATING_USER
        # The second-fault fix: an ABSOLUTE feature_yaml_path.
        assert payload.feature_yaml_path == EXPECTED_FEATURE_YAML_PATH

    @pytest.mark.asyncio
    async def test_committed_fixture_matches_freshly_driven_trigger(self) -> None:
        # Drive the production trigger live and confirm the committed bytes
        # still reflect what it emits today (payload is deterministic under
        # the fixed clock; the envelope message_id/timestamp are volatile).
        fresh = await _drive_real_trigger()
        fresh_env = MessageEnvelope.model_validate_json(fresh)
        committed_env = MessageEnvelope.model_validate_json(_load_fixture_bytes())
        assert fresh_env.payload == committed_env.payload
        assert fresh_env.source_id == committed_env.source_id == "forge"
        assert fresh_env.event_type == committed_env.event_type
        assert fresh_env.correlation_id == committed_env.correlation_id


