class _FixedClock:
    def __call__(self) -> dt.datetime:
        return dt.datetime(2026, 7, 14, 12, 0, 0, tzinfo=dt.timezone.utc)


def _load_fixture_bytes() -> bytes:
    return FIXTURE_PATH.read_bytes()


def _make_msg(data: bytes) -> AsyncMock:
    msg = AsyncMock()
    msg.data = data
    msg.ack = AsyncMock()
    return msg


def _consumer_deps(
    *,
    allowlist: list[Path] | None = None,
    approved_originators: list[str] | None = None,
    is_duplicate_terminal: bool = False,
) -> tuple[PipelineConsumerDeps, dict[str, AsyncMock]]:
    pipeline = (
        PipelineConfig(approved_originators=approved_originators)
        if approved_originators is not None
        else PipelineConfig()  # default list (now includes forge-internal)
    )
    config = ForgeConfig(
        pipeline=pipeline,
        permissions=PermissionsConfig(
            filesystem=FilesystemPermissions(
                allowlist=allowlist if allowlist is not None else [Path(CHECKOUT)]
            ),
        ),
    )
    is_dup = AsyncMock(return_value=is_duplicate_terminal)
    dispatch = AsyncMock()
    publish_failed = AsyncMock()
    deps = PipelineConsumerDeps(
        forge_config=config,
        is_duplicate_terminal=is_dup,
        dispatch_build=dispatch,
        publish_build_failed=publish_failed,
    )
    return deps, {
        "is_duplicate_terminal": is_dup,
        "dispatch_build": dispatch,
        "publish_build_failed": publish_failed,
    }


async def _drive_real_trigger() -> bytes:
    """Re-drive the REAL B3 trigger closure and return the published bytes.

    Mirrors the committed-fixture generator so a test can prove the fixture
    is not stale — the payload the production trigger emits today must still
    match the bytes on disk (modulo the volatile envelope ``message_id`` /
    ``timestamp``).
    """
    import tempfile

    from forge.adapters.sqlite import connect_writer
    from forge.cli._serve_planning import compose_planning_consumer_and_dispatch
    from forge.lifecycle import migrations as lifecycle_migrations
    from tests.integration.conftest import InMemoryNats

    broker = InMemoryNats()
    config = ForgeConfig.model_validate(
        {
            "permissions": {"filesystem": {"allowlist": [CHECKOUT]}},
            "planning": {
                "enabled": True,
                "escalation_approver": "rich",
                "target_terminal": {"enabled": True},
                "target_repo_paths": {TARGET_REPO: CHECKOUT},
            },
        }
    )
    with tempfile.TemporaryDirectory() as td:
        db_path = Path(td) / "replay.db"
        pool = connect_writer(db_path)
        lifecycle_migrations.apply_at_boot(pool)
        result = await compose_planning_consumer_and_dispatch(
            db_path=db_path,
            nats_client=broker,
            config=config,
            clock=_FixedClock(),
        )
        assert result is not None and result.driver is not None
        trigger = result.driver._deps.dispatch_build_trigger
        try:
            outcome = await trigger(
                plan_run_id=CORRELATION_ID,
                correlation_id=CORRELATION_ID,
                feature_id=FEATURE_ID,
                target_repo=TARGET_REPO,
                branch=BRANCH,
                plan_files=PLAN_FILES,
                originating_user=ORIGINATING_USER,
            )
            assert outcome.queued is True
            return broker.published[f"pipeline.build-queued.{FEATURE_ID}"][0]
        finally:
            for task in list(result.background_tasks or []):
                task.cancel()
            await asyncio.gather(
                *(result.background_tasks or []), return_exceptions=True
            )


